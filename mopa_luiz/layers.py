"""Layer model: per-layer operation type and laser parameters.

Every artwork object carries a `LayerSpec`. Disabled and frame-only layers
are visible but never emit. Raster layers emit hatch lines generated by
`mopa_luiz.raster` from their closed input shapes.
"""

from __future__ import annotations

import math
from dataclasses import asdict, dataclass
from typing import Iterable

from .cli import MarkConfig
from .safety import validate_layer_settings


VECTOR_ENGRAVE = "vector_engrave"
VECTOR_CUT = "vector_cut"
RASTER_ENGRAVE = "raster_engrave"
FRAME_ONLY = "frame_only"
DISABLED = "disabled"
OPERATIONS = (VECTOR_ENGRAVE, VECTOR_CUT, RASTER_ENGRAVE, FRAME_ONLY, DISABLED)
HATCH_PATTERNS = {"parallel": "Parallel lines", "crosshatch": "Crosshatch",
                  "contour": "Contour offsets", "radial": "Radial spokes (coupon only)"}


@dataclass
class LayerSpec:
    layer_id: str
    name: str
    operation: str
    power_percent: float
    frequency_khz: float
    pulse_width_ns: float
    speed_mm_s: float
    passes: int = 1
    visible: bool = True
    output: bool = True
    color: str = "#26d0a8"
    air_assist: bool = False
    raster_pitch_mm: float = 0.1
    raster_angle_deg: float = 0.0
    raster_angle_step_deg: float = 90.0
    crosshatch: bool = False
    hatch_pattern: str = ""

    @property
    def pattern(self) -> str:
        return self.hatch_pattern or ("crosshatch" if self.crosshatch else "parallel")

    def emits_when_marking(self) -> bool:
        if not self.output:
            return False
        if self.operation in {DISABLED, FRAME_ONLY}:
            return False
        return True

    def to_dict(self) -> dict[str, object]:
        return asdict(self)


NUMBERS = (
    "power_percent", "frequency_khz", "pulse_width_ns", "speed_mm_s",
    "raster_pitch_mm", "raster_angle_deg", "raster_angle_step_deg",
)
PASSES_ERROR = "passes must be between 1 and 999"


def _finite(value: object) -> bool:
    return isinstance(value, (int, float)) and math.isfinite(value)


def _number(payload: dict, key: str, default: float) -> float:
    value = float(payload.get(key, default))
    if not math.isfinite(value):
        raise ValueError(f"{key} must be a finite number")
    return value


def layer_from_dict(payload: dict) -> LayerSpec:
    operation = str(payload.get("operation", VECTOR_ENGRAVE))
    if operation not in OPERATIONS:
        raise ValueError(f"unknown layer operation: {operation}")
    passes = float(payload.get("passes", 1))
    if not passes.is_integer() or not 1 <= passes <= 999:
        raise ValueError(PASSES_ERROR)
    pattern = str(payload.get("hatch_pattern", ""))
    if pattern and pattern not in HATCH_PATTERNS:
        raise ValueError(f"Unknown hatch pattern: {pattern}")
    return LayerSpec(
        layer_id=str(payload.get("layer_id") or payload.get("id") or "layer"),
        name=str(payload.get("name", "Layer")),
        operation=operation,
        power_percent=_number(payload, "power_percent", 1.0),
        frequency_khz=_number(payload, "frequency_khz", 30.0),
        pulse_width_ns=_number(payload, "pulse_width_ns", 200.0),
        speed_mm_s=_number(payload, "speed_mm_s", 1000.0),
        passes=int(passes),
        visible=bool(payload.get("visible", True)),
        output=bool(payload.get("output", True)),
        color=str(payload.get("color", "#26d0a8")),
        air_assist=bool(payload.get("air_assist", False)),
        raster_pitch_mm=_number(payload, "raster_pitch_mm", 0.1),
        raster_angle_deg=_number(payload, "raster_angle_deg", 0.0),
        raster_angle_step_deg=_number(payload, "raster_angle_step_deg", 90.0),
        crosshatch=bool(payload.get("crosshatch", False)),
        hatch_pattern=pattern,
    )


def validate_layers(
    layers: Iterable[LayerSpec],
    cfg: MarkConfig | None,
) -> dict[str, list[str]]:
    """Per-layer validation. Returns layer_id -> list of errors.

    Non-finite numbers and a bad pass count are errors on every layer, even
    disabled and frame-only ones whose laser settings are otherwise unchecked.
    """
    errors: dict[str, list[str]] = {}
    for layer in layers:
        layer_errors = [f"{name} must be a finite number" for name in NUMBERS if not _finite(getattr(layer, name))]
        if not layer_errors:
            layer_errors = validate_layer_settings(
                operation=layer.operation,
                power_percent=layer.power_percent,
                frequency_khz=layer.frequency_khz,
                pulse_width_ns=layer.pulse_width_ns,
                speed_mm_s=layer.speed_mm_s,
                cfg=cfg,
            )
            if layer.operation == RASTER_ENGRAVE and layer.output and layer.raster_pitch_mm <= 0:
                layer_errors.append("raster pitch must be > 0 mm")
        if isinstance(layer.passes, bool) or not isinstance(layer.passes, int) or not 1 <= layer.passes <= 999:
            layer_errors.append(PASSES_ERROR)
        if layer_errors:
            errors[layer.layer_id] = layer_errors
    return errors
